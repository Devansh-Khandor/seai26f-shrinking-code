def load_data(path):
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        raw_rows = [row for row in reader]

    rows = []
    for row in raw_rows:
        parsed = {name: parse_value(val) for name, val in zip(header, row)}
        rows.append(parsed)

    return header, rows


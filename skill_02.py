def parse_value(v: str):
    """Parse a CSV cell: None for missing, float for numbers, else string."""
    v = v.strip()
    if v == "?":
        return None
    try:
        # Try integer first for exactness
        if "." in v:
            return float(v)
        else:
            return int(v)
    except ValueError:
        return v


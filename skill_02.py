def read_csv(path: str) -> Tuple[List[str], List[List[Any]]]:
    """Return header and list of parsed rows."""
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        rows = [list(map(parse_value, row)) for row in reader]
    return header, rows


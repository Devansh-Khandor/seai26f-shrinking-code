def nearest_neighbor_prediction(
    target_vec: List[float],
    train_vecs: List[List[float]],
    train_targets: List[float],
) -> Tuple[float, int]:
    """Find nearest neighbor and return its target and index."""
    best_i = 0
    best_dist = float("inf")
    for i, vec in enumerate(train_vecs):
        dist_sq = sum((a - b) ** 2 for a, b in zip(target_vec, vec))
        if dist_sq < best_dist:
            best_dist = dist_sq
            best_i = i
    return train_targets[best_i], best_i

def compute_std(values: List[float]) -> float:
    if not values:
        return 0.0
    mean = sum(values) / len(values)
    var = sum((x - mean) ** 2 for x in values) / len(values)
    return math.sqrt(var)


def parse_cell(v: str):
    """Parse a CSV cell: return None for missing, float for numeric, else string."""
    v = v.strip()
    if v == "?":
        return None
    # Try numeric conversion
    try:
        if "." in v:
            return float(v)
        return int(v)
    except ValueError:
        return v

def mode_value(values):
    """Return most common value among non‑None items; tie → lexicographically first."""
    counter = Counter(v for v in values if v is not None)
    if not counter:
        return None
    max_count = max(counter.values())
    common = [k for k, c in counter.items() if c == max_count]
    return min(common)  # deterministic

def numeric_mean(values):
    nums = [v for v in values if isinstance(v, (int, float))]
    return mean(nums) if nums else None


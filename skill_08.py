def split_history_arrivals(rows, n_arrivals):
    return rows[:len(rows)-n_arrivals], rows[-n_arrivals:]

# ----------------------------------------------------------------------
# Build code maps and means for adjustable columns (training data only)
# ----------------------------------------------------------------------
def build_maps_and_means(training, adjustable):
    cat_maps = {}
    num_means = {}
    is_num = {}
    for col in adjustable:
        # gather values in training
        vals = [r[col] for r in training if r[col] is not None]
        if not vals:
            is_num[col] = True
            num_means[col] = 0.0
            cat_maps[col] = {}
            continue
        if all(isinstance(v, (int, float)) for v in vals):
            is_num[col] = True
            num_means[col] = sum(v for v in vals) / len(vals)
            cat_maps[col] = {}
        else:
            is_num[col] = False
            cat_maps[col] = {v: i for i, v in enumerate(sorted(set(vals)))}
            num_means[col] = 0.0
    return cat_maps, num_means, is_num

# ----------------------------------------------------------------------
# Encode a row into numeric vector for distance
# ----------------------------------------------------------------------
def encode_row(row, adjustable, cat_maps, num_means, is_num):
    vec = []
    for col in adjustable:
        val = row.get(col)
        if val is None:
            # use mean / zero
            vec.append(num_means[col] if is_num[col] else 0)
            continue
        if is_num[col]:
            vec.append(val)
        else:
            vec.append(cat_maps[col].get(val, 0))
    return vec

# ----------------------------------------------------------------------
# Distance between two vectors (Hamming for cat, squared diff for num)
# ----------------------------------------------------------------------
def vector_distance(a, b, adjustable, is_num):
    ssd = 0.0
    for i, col in enumerate(adjustable):
        va, vb = a[i], b[i]
        if is_num[col]:
            d = va - vb
        else:
            d = 0 if va == vb else 1
        ssd += d * d
    return math.sqrt(ssd) if ssd > 0 else 0.0

# ----------------------------------------------------------------------
# Nearest neighbor prediction
# ----------------------------------------------------------------------
def predict_row(row, training_vecs, training_effort, training_defects, adjustable, cat_maps, num_means, is_num, exclude_idx=None):
    vec = encode_row(row, adjustable, cat_maps, num_means, is_num)
    best_d = None
    best_eff = None
    best_def = None
    for idx, tv in enumerate(training_vecs):
        if exclude_idx is not None and idx == exclude_idx:
            continue
        # skip rows with missing target
        if training_effort[idx] is None or training_defects[idx] is None:
            continue
        d = vector_distance(vec, tv, adjustable, is_num)
        if best_d is None or d < best_d:
            best_d = d
            best_eff = training_effort[idx]
            best_def = training_defects[idx]
    return best_eff, best_def


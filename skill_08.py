def parse_value(v: str):
    """Parse a CSV cell: None for missing, float for numbers, else string."""
    v = v.strip()
    if v == "?":
        return None
    try:
        if "." in v:
            return float(v)
        return int(v)
    except ValueError:
        return v

# ----------------------------------------------------------------------
# Load data
# ----------------------------------------------------------------------
def load_data(path):
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        rows_raw = [row for row in reader]

    rows = []
    for row in rows_raw:
        parsed = {name: parse_value(val) for name, val in zip(header, row)}
        rows.append(parsed)
    return header, rows

# ----------------------------------------------------------------------
# Column classification
# ----------------------------------------------------------------------
def classify_columns(header):
    goal_cols = [name for name in header if name.endswith(("+", "-"))]
    x_cols    = [name for name in header if name.endswith("X")]
    # adjustable: not goal, not X, not "Kloc+" (a goal)
    adjustable = [name for name in header if name not in goal_cols
                  and name not in x_cols
                  and name != "Kloc+"]
    return goal_cols, x_cols, adjustable

# ----------------------------------------------------------------------
# History / arrivals

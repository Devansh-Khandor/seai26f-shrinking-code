# ---------- helpers ----------
def parse_value(v: str):
    """Parse a CSV cell: return None for missing, else float."""
    v = v.strip()
    if v == "?":
        return None
    try:
        return float(v)
    except ValueError:
        # Should not happen for goal columns
        return None

def median(values):
    """Median of a list of numbers."""
    n = len(values)
    if n == 0:
        return None
    s = sorted(values)
    mid = n // 2
    if n % 2:
        return s[mid]
    return (s[mid - 1] + s[mid]) / 2.0

def stats(values, best_is_max):
    """Return dict with mean, median, min, max, best, worst."""
    if not values:
        return {"mean": None, "median": None, "min": None,
                "max": None, "best": None, "worst": None}
    m = mean(values)
    md = median(values)
    mn = min(values)
    mx = max(values)
    if best_is_max:
        best = mx
        worst = mn
    else:
        best = mn
        worst = mx
    return {"mean": m, "median": md, "min": mn,
            "max": mx, "best": best, "worst": worst}


def compute_feature_stats(rows, feature_names):
    """Return mean and std for numeric features, and mode for categorical."""
    stats = {}
    for name in feature_names:
        vals = [row[name] for row in rows if row[name] is not None]
        if not vals:
            stats[name] = {"mu": 0.0, "sd": 1.0, "mode": None, "numeric": True}
            continue
        numeric = all(isinstance(v, (int, float)) for v in vals)
        stats[name] = {"numeric": numeric}
        if numeric:
            mu = sum(vals) / len(vals)
            sd = math.sqrt(sum((x - mu) ** 2 for x in vals) / len(vals))
            if sd == 0:
                sd = 1e-8
            stats[name]["mu"] = mu
            stats[name]["sd"] = sd
        else:
            # mode
            mode = sorted(set(vals))[0]
            stats[name]["mode"] = mode
    return stats


# ---------- distance ----------
def dist_row(a, b, stats, feature_names):
    """Euclidean distance on numeric, Hamming on categorical."""
    ssd = 0.0
    for name in feature_names:
        va = a[name]
        vb = b[name]

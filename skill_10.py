def composite_score(row, goal_stats, goal_names):
    """Sum of z‑scores: + goals higher better, - lower better."""
    s = 0.0
    for name in goal_names:
        val = row.get(name)
        if val is None:
            continue
        mu = goal_stats[name]["mu"]
        sd = goal_stats[name]["sd"]
        z = (val - mu) / sd if name.endswith("+") else (mu - val) / sd

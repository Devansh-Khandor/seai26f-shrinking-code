class Num:
    __slots__ = ("n", "mu", "m2", "sd")

    def __init__(self):
        self.n = 0
        self.mu = 0.0
        self.m2 = 0.0
        self.sd = 0.0

    def add(self, v):
        self.n += 1
        d = v - self.mu
        self.mu += d / self.n
        self.m2 += d * (v - self.mu)
        self.sd = (self.m2 / (self.n - 1)) ** 0.5 if self.n > 1 else 0.0

def norm(col, v):
    """Logistic normalisation as in ezr."""
    z = max(-3, min(3, (v - col.mu) / (1e-32 + col.sd)))
    return 1 / (1 + math.exp(-1.7 * z))

def ydist(col_summaries, goal_cols, row):
    """Distance of row's goals to their goals."""
    n = len(goal_cols)
    if n == 0:
        return 0.0
    s = 0.0
    for at, goal in goal_cols:
        col = col_summaries[at]
        n_val = row[at]
        if n_val is None:
            continue  # ignore missing goals
        n_norm = norm(col, n_val)
        s += (abs(n_norm - goal) ** 2)
    return math.sqrt(s / n)


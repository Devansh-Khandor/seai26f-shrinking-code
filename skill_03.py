def median(values: List[float]) -> float:
    """Median of a list of numbers."""
    n = len(values)
    if n == 0:
        return float("nan")
    s = sorted(values)
    mid = n // 2
    if n % 2:
        return s[mid]
    return (s[mid - 1] + s[mid]) / 2.0


def ks(xs: List[float], ys: List[float], a: float = 1.36) -> bool:
    """Sorted in.  95% Kolmogorov–Smirnov."""
    n, m, i, j, d = len(xs), len(ys), 0, 0, 0
    while i < n and j < m:
        v = min(xs[i], ys[j])
        while i < n and xs[i] <= v:
            i += 1
        while j < m and ys[j] <= v:
            j += 1
        d = max(d, abs(i / n - j / m))
    return d <= a * (n + m) ** 0.5 / (n * m) ** 0.5


def cliffs(xs: List[float], ys: List[float], d: float = 0.197) -> bool:
    """Sorted in.  Is the rank imbalance small enough?"""
    gt = lt = j = k = 0
    for x in xs:
        while j < len(ys) and ys[j] < x:
            j += 1
            k = j
        while k < len(ys) and ys[k] <= x:
            k += 1
        gt += j
        lt += len(ys) - k
    return abs(gt - lt) / (len(xs) * len(ys)) <= d


def same(xs: List[float], ys: List[float], eps: float = 0) -> bool:
    """
    Indistinguishable.  Always cliffs and ks; EPS adds cohen, and
    doubles as its effect size (eps=0 skips that third test).
    """
